#!/usr/bin/env python3
"""Netlist <-> firmware pin header.

    pinmap.py gen   hwlab.net [--mcu U1] > firmware/include/board_pins.h
    pinmap.py check hwlab.net firmware/include/board_pins.h [--mcu U1]

`gen` emits `#define PIN_<NET> <gpio>` for every MCU pin on a signal net.
`check` parses the header's `#define PIN_* <n>` lines and compares them with the
netlist *semantically* (comments, order and extra non-PIN_ macros are ignored);
exit 1 and a readable diff on any mismatch: missing, extra or different GPIO.
Stdlib only (uses tools/kisexpr.py).
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import kisexpr as k  # noqa: E402

# ESP32-S3-WROOM-1 pin functions that are not spelled IOn in the symbol
SPECIAL = {"TXD0": 43, "RXD0": 44, "USB_D-": 19, "USB_D+": 20}
SKIP_NETS = {"GND", "+3V3", "VBUS"}
DEFINE = re.compile(r"^\s*#\s*define\s+(PIN_[A-Z0-9_]+)\s+\(?\s*(\d+)\s*\)?", re.M)


def macro(net: str) -> str:
    return "PIN_" + re.sub(r"[^A-Z0-9]+", "_", net.upper()).strip("_")


def from_netlist(path: Path, mcu: str) -> dict[str, tuple[int, str]]:
    t = k.load(path)
    out: dict[str, tuple[int, str]] = {}
    for n in k.children(k.find(t, "nets"), "net"):
        name = str(k.find(n, "name")[1]).lstrip("/")
        if name in SKIP_NETS or name.startswith("unconnected-") or name.startswith("Net-("):
            continue
        for node in k.children(n, "node"):
            if str(k.find(node, "ref")[1]) != mcu:
                continue
            fn = k.find(node, "pinfunction")
            fn = str(fn[1]) if fn else ""
            pin = str(k.find(node, "pin")[1])
            if fn.endswith("_" + pin):  # KiCad 10 writes pinfunction as NAME_NUMBER
                fn = fn[: -len(pin) - 1]
            m = re.fullmatch(r"IO(\d+)", fn)
            gpio = int(m.group(1)) if m else SPECIAL.get(fn)
            if gpio is None:
                continue  # EN, power pins ...
            out[macro(name)] = (gpio, f"{mcu} pin {pin} ({fn}), net {name}")
    return out


def gen(pins: dict[str, tuple[int, str]], source: str) -> str:
    w = max(map(len, pins)) + 1
    lines = [
        f"// Generated by tools/pinmap.py from {source}. Do not edit by hand:",
        "// change the schematic, then regenerate. CI fails if this drifts.",
        "#pragma once",
        "",
    ]
    for name, (gpio, why) in sorted(pins.items(), key=lambda kv: kv[1][0]):
        lines.append(f"#define {name:<{w}} {gpio:>2}  // {why}")
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("mode", choices=["gen", "check"])
    ap.add_argument("netlist", type=Path)
    ap.add_argument("header", type=Path, nargs="?")
    ap.add_argument("--mcu", default="U1")
    a = ap.parse_args()
    pins = from_netlist(a.netlist, a.mcu)
    if a.mode == "gen":
        sys.stdout.write(gen(pins, "hardware/hwlab.kicad_sch"))
        return 0
    have = {m: int(v) for m, v in DEFINE.findall(a.header.read_text())}
    want = {m: g for m, (g, _) in pins.items()}
    problems = []
    for m in sorted(want.keys() | have.keys()):
        if m not in have:
            problems.append(f"  missing in header: #define {m} {want[m]}   ({pins[m][1]})")
        elif m not in want:
            problems.append(f"  not in schematic:  #define {m} {have[m]}")
        elif have[m] != want[m]:
            problems.append(f"  MISMATCH {m}: header says GPIO{have[m]}, schematic says GPIO{want[m]} ({pins[m][1]})")
    if problems:
        print(f"pin map check FAILED: {a.header} vs {a.netlist}")
        print("\n".join(problems))
        print("fix: python tools/pinmap.py gen <netlist> > " + str(a.header))
        return 1
    print(f"pin map OK: {len(want)} pins match ({a.header})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
